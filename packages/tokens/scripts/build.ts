/**
 * Emits dist/tokens.css (CSS custom properties, light + dark) and dist/tokens.json.
 * Dark theme applies via prefers-color-scheme or [data-theme="dark"]; [data-theme="light"] forces light.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  brand, fusion, gradients, toCssGradient, themes, typography, fontFamily, type ColorTheme,
} from '../src/index.js';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist');
mkdirSync(out, { recursive: true });

const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/\./g, '-').toLowerCase();

function flatten(obj: unknown, prefix: string, acc: Record<string, string> = {}): Record<string, string> {
  if (typeof obj === 'string') { acc[prefix] = obj; return acc; }
  if (Array.isArray(obj)) { obj.forEach((v, i) => flatten(v, `${prefix}-${i + 1}`, acc)); return acc; }
  if (obj && typeof obj === 'object') {
    for (const [k, v] of Object.entries(obj)) if (k !== 'name') flatten(v, prefix ? `${prefix}-${kebab(k)}` : kebab(k), acc);
  }
  return acc;
}

const themeVars = (t: ColorTheme) =>
  Object.entries(flatten(t, '')).map(([k, v]) => `  --yh-${k}: ${v};`).join('\n');

const staticVars: string[] = [
  ...Object.entries(brand).map(([k, v]) => `  --yh-${kebab(k)}: ${v};`),
  ...Object.entries(fusion).map(([k, v]) => `  --yh-fusion-${k}: ${v};`),
  ...Object.entries(gradients).map(([k, g]) => `  --yh-gradient-${kebab(k)}: ${toCssGradient(g)};`),
  `  --yh-font-primary: ${fontFamily.primary.map((f) => (f.includes(' ') ? `"${f}"` : f)).join(', ')};`,
  ...Object.entries(typography).flatMap(([k, s]) => {
    const n = kebab(k);
    return [
      `  --yh-type-${n}-size: ${s.fontSize / 16}rem;`,
      `  --yh-type-${n}-weight: ${s.fontWeight};`,
      `  --yh-type-${n}-line-height: ${s.lineHeight};`,
    ];
  }),
];

const css = `/* Generated by @yuhshi/tokens — do not edit. Source: Yuhshi Master Blueprint Parts XV–XVI. */
:root {
${staticVars.join('\n')}
${themeVars(themes.light)}
  color-scheme: light dark;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${themeVars(themes.dark)}
  }
}
[data-theme="dark"] {
${themeVars(themes.dark)}
}
.yh-tabular { font-variant-numeric: tabular-nums; }
`;

writeFileSync(join(out, 'tokens.css'), css);
writeFileSync(join(out, 'tokens.json'), JSON.stringify({ brand, fusion, gradients, themes, typography, fontFamily }, null, 2));
console.log(`tokens.css (${css.split('\n').length} lines) and tokens.json written to dist/`);
